def evaluate_soccer_corner_kicks_and_asian_handicap(
    *,
    home_team: str = "Arsenal",
    away_team: str = "Chelsea",
    home_corners_for_pg: float = 6.35,
    away_corners_allowed_pg: float = 4.65,
    away_corners_for_pg: float = 5.10,
    home_corners_allowed_pg: float = 4.05,
    lambda_home_goals: float = 1.68,
    lambda_away_goals: float = 1.06,
    rho_dc: float = -0.10,
    ppda_home: float = 8.4,
    ppda_away: float = 10.6,
    repo_root: Path | None = None,
) -> dict[str, Any]:
    """Evaluate Soccer Corner Kicks PMF and exact Quarter-Goal Asian Handicap splits."""
    from gse_engine.multisport.daily_multisport_slate_engine import build_dixon_coles_pmf

    vault, is_fb = _load_universal_vault(repo_root)
    sb = vault.get("soccer_epl_corners_and_match_baselines", {}) if not is_fb else {}
    mb = sb.get("match_baselines", {})
    lg_hm_crn = float(mb.get("home_corners_mean", 5.4263))
    lg_aw_crn = float(mb.get("away_corners_mean", 4.8711))
    lg_tot_crn = float(mb.get("total_corners_mean", 10.2974))

    exp_hm_crn = _clip(
        (float(home_corners_for_pg) * float(away_corners_allowed_pg)) / max(1.0, lg_hm_crn),
        1.5,
        11.5,
    )
    exp_aw_crn = _clip(
        (float(away_corners_for_pg) * float(home_corners_allowed_pg)) / max(1.0, lg_aw_crn),
        1.2,
        10.5,
    )
    exp_tot_crn = exp_hm_crn + exp_aw_crn

    # Corner-handicap distribution via independent Skellam grid (0..22)
    max_c = 22
    hc_pmf = np.array(
        [
            math.exp(k * math.log(exp_hm_crn) - exp_hm_crn - math.lgamma(float(k) + 1.0))
            for k in range(max_c + 1)
        ]
    )
    ac_pmf = np.array(
        [
            math.exp(k * math.log(exp_aw_crn) - exp_aw_crn - math.lgamma(float(k) + 1.0))
            for k in range(max_c + 1)
        ]
    )
    hc_pmf /= np.sum(hc_pmf)
    ac_pmf /= np.sum(ac_pmf)
    c_grid = np.outer(hc_pmf, ac_pmf)
    hi_c, ai_c = np.indices((max_c + 1, max_c + 1))
    home_crn_minus_1_5 = float(np.sum(c_grid[(hi_c - ai_c) > 1.5]))

    pmf = build_dixon_coles_pmf(lambda_home_goals, lambda_away_goals, rho_dc=rho_dc, max_goals=10)
    hg, ag = np.indices(pmf.shape)
    diff = hg - ag

    def _ah_split(line: float) -> dict[str, float]:
        # Decompose quarter-goal handicap (e.g., -0.75 = 50% -0.5 + 50% -1.0)
        rem = abs(line * 4.0) - round(abs(line * 4.0))
        assert rem < 1e-6
        q_idx = round(line * 4.0)
        if q_idx % 2 == 0:
            l1, l2 = line, line
        else:
            l1, l2 = line - 0.25, line + 0.25
        win_full = float(np.sum(pmf[(diff + l1 > 1e-9) & (diff + l2 > 1e-9)]))
        half_win = float(
            np.sum(
                pmf[
                    ((diff + l1 > 1e-9) & (np.abs(diff + l2) < 1e-9))
                    | ((diff + l2 > 1e-9) & (np.abs(diff + l1) < 1e-9))
                ]
            )
        )
        push = float(np.sum(pmf[(np.abs(diff + l1) < 1e-9) & (np.abs(diff + l2) < 1e-9)]))
        half_loss = float(
            np.sum(
                pmf[
                    ((diff + l1 < -1e-9) & (np.abs(diff + l2) < 1e-9))
                    | ((diff + l2 < -1e-9) & (np.abs(diff + l1) < 1e-9))
                ]
            )
        )
        loss_full = float(np.sum(pmf[(diff + l1 < -1e-9) & (diff + l2 < -1e-9)]))
        ev_prob = win_full + 0.75 * half_win + 0.50 * push + 0.25 * half_loss
        return {
            "line": round(line, 2),
            "win_prob": round(win_full, 5),
            "half_win_prob": round(half_win, 5),
            "push_prob": round(push, 5),
            "half_loss_prob": round(half_loss, 5),
            "loss_prob": round(loss_full, 5),
            "expected_settlement_share": round(ev_prob, 5),
        }

    p_home_win = float(np.sum(pmf[diff > 0]))
    p_draw = float(np.sum(pmf[diff == 0]))
    p_away_win = float(np.sum(pmf[diff < 0]))
    field_tilt_home = round(
        100.0
        * (1.0 / max(4.0, ppda_home))
        / ((1.0 / max(4.0, ppda_home)) + (1.0 / max(4.0, ppda_away))),
        2,
    )

    return {
        "schema": "wave40_soccer_corners_and_asian_handicap_v1",
        "clean_checkout_fallback": is_fb,
        "matchup": f"{home_team} vs {away_team}",
        "epl_matches_sample_n": int(sb.get("matches_count", 0)),
        "epl_clubs_count": int(sb.get("clubs_count", 0)),
        "league_total_corners_mean": round(lg_tot_crn, 4),
        "expected_home_corners": round(exp_hm_crn, 3),
        "expected_away_corners": round(exp_aw_crn, 3),
        "expected_total_corners": round(exp_tot_crn, 3),
        "over_9_5_corners_prob": round(_poisson_tail(exp_tot_crn, 10), 4),
        "over_10_5_corners_prob": round(_poisson_tail(exp_tot_crn, 11), 4),
        "over_11_5_corners_prob": round(_poisson_tail(exp_tot_crn, 12), 4),
        "home_corner_handicap_minus_1_5_prob": round(home_crn_minus_1_5, 4),
        "set_piece_corner_xg_home": round(exp_hm_crn * 0.032, 3),
        "field_tilt_home_pct": field_tilt_home,
        "dixon_coles_1x2": {
            "home_win": round(p_home_win, 5),
            "draw": round(p_draw, 5),
            "away_win": round(p_away_win, 5),
        },
        "asian_handicaps_home": {
            "ah_minus_0_25": _ah_split(-0.25),
            "ah_minus_0_50": _ah_split(-0.50),
            "ah_minus_0_75": _ah_split(-0.75),
            "ah_plus_0_25": _ah_split(0.25),
            "ah_plus_0_75": _ah_split(0.75),
        },
        "real_money_stake_cleared": REAL_MONEY_STAKE_CLEARED,
        "live_stake_fraction": LIVE_STAKE_FRACTION,
    }


