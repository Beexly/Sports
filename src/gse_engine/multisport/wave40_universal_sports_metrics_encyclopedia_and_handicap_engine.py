@lru_cache(maxsize=256)
def _hold_prob(p: float) -> float:
    """Exact probability server holds a standard tennis service game."""
    q = 1.0 - p
    direct = (p**4) * (1.0 + 4.0 * q + 10.0 * (q**2))
    reach_deuce = 20.0 * (p**3) * (q**3)
    win_deuce = (p**2) / max(1e-12, (p**2) + (q**2))
    return float(direct + reach_deuce * win_deuce)


@lru_cache(maxsize=256)
def _tiebreak_prob(p_a: float, p_b: float) -> float:
    """Exact 7-point tiebreak win prob for Player A serving point 0."""
    # Server schedule in TB: k=0 -> A; k=1,2 -> B; k=3,4 -> A; ...
    p_win_deuce = (p_a * (1.0 - p_b)) / max(1e-12, p_a * (1.0 - p_b) + (1.0 - p_a) * p_b)
    dp: dict[tuple[int, int], float] = {}
    for s in range(12, -1, -1):
        for a in range(7):
            b = s - a
            if b < 0 or b > 6:
                continue
            if a == 6 and b == 6:
                dp[(6, 6)] = p_win_deuce
                continue
            k = a + b
            a_serves = (((k + 1) // 2) % 2) == 0
            p_pt = p_a if a_serves else (1.0 - p_b)
            win_a = 1.0 if a + 1 == 7 else dp[(a + 1, b)]
            win_b = 0.0 if b + 1 == 7 else dp[(a, b + 1)]
            dp[(a, b)] = p_pt * win_a + (1.0 - p_pt) * win_b
    return float(dp[(0, 0)])


def _single_set_distribution(p_a: float, p_b: float) -> dict[tuple[int, int], float]:
    """Exact 14-outcome set score distribution averaging first-server parity."""
    ha = _hold_prob(p_a)
    hb = _hold_prob(p_b)
    tb_ab = _tiebreak_prob(p_a, p_b)
    tb_ba = 1.0 - _tiebreak_prob(p_b, p_a)
    tb_avg = 0.5 * (tb_ab + tb_ba)

    combined: dict[tuple[int, int], float] = {}
    for first_a in (True, False):
        state_probs: dict[tuple[int, int], float] = {(0, 0): 1.0}
        term: dict[tuple[int, int], float] = {}
        for g_tot in range(13):
            next_sp: dict[tuple[int, int], float] = {}
            a_serves_game = ((g_tot % 2) == 0) if first_a else ((g_tot % 2) == 1)
            p_game_a = ha if a_serves_game else (1.0 - hb)
            for ga in range(7):
                gb = g_tot - ga
                if gb < 0 or gb > 6 or (ga, gb) not in state_probs:
                    continue
                pr = state_probs[(ga, gb)]
                if ga == 6 and gb == 6:
                    term[(7, 6)] = term.get((7, 6), 0.0) + pr * tb_avg
                    term[(6, 7)] = term.get((6, 7), 0.0) + pr * (1.0 - tb_avg)
                    continue
                if ga == 6 and gb == 5:
                    term[(7, 5)] = term.get((7, 5), 0.0) + pr * p_game_a
                    next_sp[(6, 6)] = next_sp.get((6, 6), 0.0) + pr * (1.0 - p_game_a)
                    continue
                if ga == 5 and gb == 6:
                    next_sp[(6, 6)] = next_sp.get((6, 6), 0.0) + pr * p_game_a
                    term[(5, 7)] = term.get((5, 7), 0.0) + pr * (1.0 - p_game_a)
                    continue
                # Non-5-6 transition
                if ga + 1 == 6 and gb <= 4:
                    term[(6, gb)] = term.get((6, gb), 0.0) + pr * p_game_a
                else:
                    next_sp[(ga + 1, gb)] = next_sp.get((ga + 1, gb), 0.0) + pr * p_game_a
                if gb + 1 == 6 and ga <= 4:
                    term[(ga, 6)] = term.get((ga, 6), 0.0) + pr * (1.0 - p_game_a)
                else:
                    next_sp[(ga, gb + 1)] = next_sp.get((ga, gb + 1), 0.0) + pr * (1.0 - p_game_a)
            state_probs = next_sp
        for sc, pr in term.items():
            combined[sc] = combined.get(sc, 0.0) + 0.5 * pr
    return combined


def evaluate_tennis_markov_game_and_set_handicaps(
    *,
    tour: str = "ATP",
    surface: str = "Hard",
    best_of: int = 3,
    player_a_serve_pct_adj: float = 0.025,
    player_a_return_pct_adj: float = 0.018,
    player_b_serve_pct_adj: float = -0.012,
    player_b_return_pct_adj: float = -0.008,
    elo_diff_a_minus_b: float = 120.0,
    repo_root: Path | None = None,
) -> dict[str, Any]:
    """Run Barnett-Clarke Markov chain for Tennis Match, Set Handicap, and Game Handicap."""
    vault, is_fb = _load_universal_vault(repo_root)
    tb = vault.get("tennis_atp_wta_and_surface_baselines", {}) if not is_fb else {}
    surf_map = tb.get("surface_baselines", {})
    key = f"{tour.strip().upper()}_{surface.strip().title()}"
    sbase = surf_map.get(key, {"service_pts_won_pct": 0.654, "court_pace_index": 36.5})
    lg_spw = float(sbase["service_pts_won_pct"])
    elo_shift = 0.00018 * float(elo_diff_a_minus_b)

    p_a = _clip(
        lg_spw + float(player_a_serve_pct_adj) - float(player_b_return_pct_adj) + elo_shift,
        0.42,
        0.86,
    )
    p_b = _clip(
        lg_spw + float(player_b_serve_pct_adj) - float(player_a_return_pct_adj) - elo_shift,
        0.42,
        0.86,
    )
    dominance_ratio = (1.0 - p_b) / max(1e-6, 1.0 - p_a)

    set_dist = _single_set_distribution(p_a, p_b)
    target_sets = 3 if int(best_of) == 5 else 2
    max_sets = 5 if int(best_of) == 5 else 3

    # Exact DP over (sets_a, sets_b, games_a, games_b)
    active: dict[tuple[int, int, int, int], float] = {(0, 0, 0, 0): 1.0}
    completed: dict[tuple[int, int, int, int], float] = {}
    for _ in range(max_sets):
        nxt: dict[tuple[int, int, int, int], float] = {}
        for (sa, sb, ga, gb), pr in active.items():
            for (dga, dgb), spr in set_dist.items():
                dsa = 1 if dga > dgb else 0
                dsb = 1 - dsa
                nsa, nsb, nga, ngb = sa + dsa, sb + dsb, ga + dga, gb + dgb
                val = pr * spr
                if nsa == target_sets or nsb == target_sets:
                    completed[(nsa, nsb, nga, ngb)] = completed.get((nsa, nsb, nga, ngb), 0.0) + val
                else:
                    nxt[(nsa, nsb, nga, ngb)] = nxt.get((nsa, nsb, nga, ngb), 0.0) + val
        active = nxt

    pmf_sum = sum(completed.values())
    win_a = sum(pr for (sa, sb, _, _), pr in completed.items() if sa > sb)
    win_b = sum(pr for (sa, sb, _, _), pr in completed.items() if sb > sa)
    exp_ga = sum(float(ga) * pr for (_, _, ga, _), pr in completed.items())
    exp_gb = sum(float(gb) * pr for (_, _, _, gb), pr in completed.items())

    def _game_hcap_stats(line: float) -> dict[str, float]:
        w_p = sum(pr for (_, _, ga, gb), pr in completed.items() if float(ga - gb) + line > 1e-9)
        push_p = sum(
            pr for (_, _, ga, gb), pr in completed.items() if abs(float(ga - gb) + line) < 1e-9
        )
        l_p = sum(pr for (_, _, ga, gb), pr in completed.items() if float(ga - gb) + line < -1e-9)
        return {
            "win_prob": round(w_p, 5),
            "push_prob": round(push_p, 5),
            "loss_prob": round(l_p, 5),
        }

    game_handicaps = {
        f"{ln:+.1f}": _game_hcap_stats(ln)
        for ln in (-5.5, -4.5, -3.5, -3.0, -2.5, -1.5, 1.5, 2.5, 3.0, 3.5, 4.5, 5.5)
    }
    set_handicaps: dict[str, float] = {
        "a_minus_1_5": round(
            sum(pr for (sa, sb, _, _), pr in completed.items() if (sa - sb) > 1.5), 5
        ),
        "a_plus_1_5": round(
            sum(pr for (sa, sb, _, _), pr in completed.items() if (sa - sb) > -1.5), 5
        ),
    }
    if target_sets == 3:
        set_handicaps["a_minus_2_5"] = round(
            sum(pr for (sa, sb, _, _), pr in completed.items() if (sa - sb) > 2.5), 5
        )
        set_handicaps["a_plus_2_5"] = round(
            sum(pr for (sa, sb, _, _), pr in completed.items() if (sa - sb) > -2.5), 5
        )

    totals = {
        f"over_{t:.1f}": round(
            sum(pr for (_, _, ga, gb), pr in completed.items() if (ga + gb) > t), 5
        )
        for t in ((36.5, 38.5) if target_sets == 3 else (20.5, 21.5, 22.5, 23.5))
    }

    return {
        "schema": "wave40_tennis_markov_handicaps_v1",
        "clean_checkout_fallback": is_fb,
        "tour": tour.upper(),
        "surface": surface.title(),
        "best_of": int(best_of),
        "court_pace_index": float(sbase["court_pace_index"]),
        "atp_top100_count": len(tb.get("atp_top100", [])),
        "wta_top100_count": len(tb.get("wta_top100", [])),
        "player_a_spw_prob": round(p_a, 5),
        "player_b_spw_prob": round(p_b, 5),
        "player_a_hold_prob": round(_hold_prob(p_a), 5),
        "player_b_hold_prob": round(_hold_prob(p_b), 5),
        "player_a_dominance_ratio": round(dominance_ratio, 4),
        "pmf_total_mass": round(pmf_sum, 12),
        "player_a_match_win_prob": round(win_a, 5),
        "player_b_match_win_prob": round(win_b, 5),
        "expected_games_a": round(exp_ga, 3),
        "expected_games_b": round(exp_gb, 3),
        "expected_total_games": round(exp_ga + exp_gb, 3),
        "expected_game_handicap_margin": round(exp_ga - exp_gb, 3),
        "set_handicaps": set_handicaps,
        "game_handicaps": game_handicaps,
        "total_games_thresholds": totals,
        "real_money_stake_cleared": REAL_MONEY_STAKE_CLEARED,
        "live_stake_fraction": LIVE_STAKE_FRACTION,
    }


def evaluate_cfb_nba_golf_mma_metrics_suite(
    repo_root: Path | None = None,
) -> dict[str, Any]:
    """Evaluate real baselines and composite models across CFB, NBA, PGA Golf, and UFC/MMA."""
    vault, is_fb = _load_universal_vault(repo_root)
    nba_b = vault.get("nba_30_teams_baselines", {}) if not is_fb else {}
    cfb_b = vault.get("ncaaf_fbs_and_line_yards_baselines", {}) if not is_fb else {}
    gm_b = vault.get("golf_pga_and_mma_ufc_baselines", {}) if not is_fb else {}

    nba_lg = nba_b.get("league_baselines", {})
    efg = float(nba_lg.get("four_factors_baseline_efg", 0.543))
    tov = float(nba_lg.get("four_factors_baseline_tov", 0.128))
    oreb = float(nba_lg.get("four_factors_baseline_oreb", 0.252))
    ftr = float(nba_lg.get("four_factors_baseline_ftr", 0.214))
    four_factors_base = round(0.40 * efg - 0.25 * tov + 0.20 * oreb + 0.15 * ftr, 5)

    pga_lg = gm_b.get("pga_tour_baselines", {})
    ufc_lg = gm_b.get("ufc_mma_baselines", {})
    cfb_lg = cfb_b.get("league_baselines", {})

    from gse_engine.memory.knowledge_continuity_and_gsi_rlvr_flywheel import (
        DIMENSIONLESS,
        DimensionVector,
        StudyEffect,
        pool_pet_peese_meta_regression,
    )

    meta_pool = pool_pet_peese_meta_regression(
        [
            StudyEffect("cfb_sp_plus", 0.28, 0.06, 1.0, 220.0),
            StudyEffect("nba_four_factors", 0.31, 0.05, 1.0, 360.0),
            StudyEffect("mlb_barrel_xwoba", 0.24, 0.06, 1.0, 251.0),
            StudyEffect("tennis_markov_elo", 0.34, 0.05, 1.0, 400.0),
        ]
    )
    re_tau2 = float(meta_pool["tau_squared"])
    re_i2 = float(meta_pool["i_squared"])
    dim_tag: DimensionVector = DIMENSIONLESS
    assert dim_tag == (0, 0, 0, 0, 0, 0)

    return {
        "schema": "wave40_cfb_nba_golf_mma_baselines_v1",
        "clean_checkout_fallback": is_fb,
        "nba_teams_count": int(nba_b.get("teams_count", 0)),
        "nba_ppg_mean": float(nba_lg.get("ppg_mean", 113.572)),
        "nba_four_factors_composite_baseline": four_factors_base,
        "cfb_fbs_teams_count": int(cfb_b.get("fbs_teams_count", 0)),
        "cfb_ppg_mean": float(cfb_lg.get("ppg_mean", 27.931)),
        "cfb_havoc_rate_mean": float(cfb_lg.get("havoc_rate_mean", 0.168)),
        "cfb_adj_line_yards_mean": float(cfb_lg.get("adj_line_yards_mean", 3.05)),
        "pga_driving_dist_mean": float(pga_lg.get("driving_distance_yds_mean", 300.2)),
        "pga_gir_pct_mean": float(pga_lg.get("gir_pct_mean", 66.5)),
        "ufc_slpm_mean": float(ufc_lg.get("slpm_mean", 3.85)),
        "ufc_td_def_pct_mean": float(ufc_lg.get("td_def_pct_mean", 62.5)),
        "cross_sport_signal_tau2": round(float(re_tau2), 6),
        "cross_sport_signal_i2": round(float(re_i2), 4),
    }


def evaluate_wave40_universal_multisport_metrics_suite(
    repo_root: Path | None = None,
) -> dict[str, Any]:
    """Synthesize the 284-metric encyclopedia and all 5 sport-specific quantitative engines."""
    root = _resolve_root(repo_root)
    ck = str(root)
    if ck in _SUITE40_MS_CACHE:
        return _SUITE40_MS_CACHE[ck]

    _, is_fb = _load_universal_vault(root)
    sports_counts: dict[str, int] = {}
    for spec in UNIVERSAL_SPORTS_METRICS_REGISTRY:
        sports_counts[spec.sport] = sports_counts.get(spec.sport, 0) + 1

    mlb = evaluate_mlb_statcast_barrel_and_pitch_arsenal(repo_root=root)
    soccer = evaluate_soccer_corner_kicks_and_asian_handicap(repo_root=root)
    nhl = evaluate_nhl_special_teams_ppp_and_penalty_play(repo_root=root)
    tennis_atp = evaluate_tennis_markov_game_and_set_handicaps(
        tour="ATP", surface="Hard", best_of=3, repo_root=root
    )
    tennis_wta = evaluate_tennis_markov_game_and_set_handicaps(
        tour="WTA", surface="Clay", best_of=3, repo_root=root
    )
    cfb_nba = evaluate_cfb_nba_golf_mma_metrics_suite(repo_root=root)

    # Probe exact founder requested metrics across encyclopedia
    probe_queries = {
        "barrel_pct": query_universal_sport_metric(
            "barrel percentage", sport="MLB", repo_root=root
        )["metric_id"],
        "corner_kicks": query_universal_sport_metric(
            "corner kicks", sport="SOCCER", repo_root=root
        )["metric_id"],
        "penalty_play_pts": query_universal_sport_metric(
            "penalty play points", sport="NHL", repo_root=root
        )["metric_id"],
        "tennis_handicaps": query_universal_sport_metric(
            "handicaps for tennis", sport="TENNIS", repo_root=root
        )["metric_id"],
        "cfb_havoc": query_universal_sport_metric("havoc rate", sport="NCAAF", repo_root=root)[
            "metric_id"
        ],
        "nba_efg": query_universal_sport_metric("efg%", sport="NBA", repo_root=root)["metric_id"],
    }

    summary: dict[str, Any] = {
        "schema": "wave40_universal_multisport_metrics_suite_v1",
        "wired": True,
        "clean_checkout_fallback": is_fb,
        "total_canonical_metrics": len(UNIVERSAL_SPORTS_METRICS_REGISTRY),
        "sports_covered_count": len(sports_counts),
        "sports_metric_counts": sports_counts,
        "founder_probe_resolutions": probe_queries,
        "mlb_statcast_summary": mlb,
        "soccer_corners_asian_handicap": soccer,
        "nhl_special_teams_ppp_shp": nhl,
        "tennis_markov_atp_hard": tennis_atp,
        "tennis_markov_wta_clay": tennis_wta,
        "cfb_nba_golf_mma": cfb_nba,
        "real_money_stake_cleared": REAL_MONEY_STAKE_CLEARED,
        "live_stake_fraction": LIVE_STAKE_FRACTION,
    }
    blob = json.dumps(summary, indent=2, ensure_ascii=True)
    summary["suite_sha256"] = hashlib.sha256(blob.encode("ascii")).hexdigest()
    _SUITE40_MS_CACHE[ck] = summary
    return summary
