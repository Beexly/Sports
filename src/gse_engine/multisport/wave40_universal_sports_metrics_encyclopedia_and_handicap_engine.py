def _poisson_tail(lam: float, min_k: int) -> float:
    """Compute P(X >= min_k) for Poisson(lam) deterministically via log-gamma."""
    lam_s = max(1e-6, float(lam))
    cdf = 0.0
    for k in range(max(0, int(min_k))):
        cdf += math.exp(k * math.log(lam_s) - lam_s - math.lgamma(float(k) + 1.0))
    return float(_clip(1.0 - cdf, 0.0, 1.0))


