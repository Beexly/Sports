/**
 * FBS conference -> team -> ESPN id map (ledger C-176, NCAA Specialist).
 *
 * Source: live ESPN core API, fetched 2026-09-09 00:0x UTC, no key, no login:
 *   https://sports.core.api.espn.com/v2/sports/football/leagues/college-football/
 *     seasons/2026/types/2/groups/80/children  (11 conferences)
 *     seasons/2026/types/2/groups/{conferenceId}/teams  (member teams per conference)
 *     seasons/2026/teams/{espnId}  (team detail: displayName, shortDisplayName,
 *     location, abbreviation, slug)
 * Same free, cleared ESPN public source apps/web/lib/data-sources/free-adapters/
 * espn-scores.ts already uses for group 80/81 boards (approved_public_logged_off,
 * facts only). 138 FBS teams across 11 conferences, verified live for the 2026 season.
 * FBS Independents is ESPN's own grouping body for programs with no conference, kept
 * here with isIndependent=true rather than a synthetic 12th conference.
 *
 * cfbdId is intentionally always null: CollegeFootballData (CFBD) ingestion is BLOCKED
 * (source-rights-registry.ts, status vendor_candidate; see
 * docs/ops/CFBD_TERMS_EVIDENCE_2026-09-08.md) and this repo holds no CFBD API key, so no
 * CFBD id can be verified today (rule 1: no fabricated data - an invented id is worse
 * than a missing one). Populate cfbdId from a live CFBD /teams call once a key is
 * approved and the adapter lands; never hand-guess it.
 *
 * Do not hand-edit team rows below; regenerate from the same live endpoints if ESPN
 * renames, relocates, or realigns a program (conference realignment happens most
 * offseasons). This file is a reference table, not the source of truth for a live
 * board - espn-scores.ts still reads scores live.
 */

export interface FbsConferenceTeam {
  /** ESPN numeric team id, e.g. "2" for Auburn. Stable across seasons. */
  readonly espnId: string;
  /** e.g. "Auburn Tigers". */
  readonly displayName: string;
  /** ESPN's own short form, e.g. "Ole Miss" for "Ole Miss Rebels", "FIU" for
   * "Florida International Panthers". The verified alias source below. */
  readonly shortDisplayName: string;
  /** e.g. "Auburn". */
  readonly location: string;
  /** e.g. "Tigers". */
  readonly name: string;
  /** e.g. "AUB". */
  readonly abbreviation: string;
  /** e.g. "auburn-tigers". */
  readonly slug: string;
  /** ESPN group id for the team's conference, e.g. "8" for the SEC. */
  readonly conferenceId: string;
  /** e.g. "Southeastern Conference". */
  readonly conferenceName: string;
  /** e.g. "SEC". */
  readonly conferenceShortName: string;
  /** True only for the "FBS Independents" body (not a real conference). */
  readonly isIndependent: boolean;
  /**
   * CollegeFootballData team id. Always null today - see file header. Never fabricate
   * this value; a wrong id silently mis-joins a game to the wrong program.
   */
  readonly cfbdId: string | null;
}

