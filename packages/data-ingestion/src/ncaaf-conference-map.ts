/** Lookup by ESPN numeric id (as returned in scoreboard competitor.team.id). */
export const FBS_TEAM_BY_ESPN_ID: ReadonlyMap<string, FbsConferenceTeam> = new Map(
  FBS_CONFERENCE_TEAMS.map((t) => [t.espnId, t]),
)

/** Lookup by ESPN slug (stable, lowercase-hyphenated; e.g. odds feeds keyed on slug). */
export const FBS_TEAM_BY_SLUG: ReadonlyMap<string, FbsConferenceTeam> = new Map(
  FBS_CONFERENCE_TEAMS.map((t) => [t.slug, t]),
)

/**
 * Lookup by every exact name string ESPN itself reports for a team: displayName AND
 * shortDisplayName ("Ole Miss Rebels" -> also keyed under "Ole Miss"). Both come from
 * the same fetch as the table above, so this is not a guessed alias list - only names
 * ESPN itself uses. game-identity.ts disables prefix matching on purpose ("Texas" is a
 * prefix of "Texas Tech", "Miami" of "Miami (OH)", "Washington" of "Washington State"),
 * so a spelling mismatch must be solved by an exact alias, never a looser match.
 *
 * This does NOT cover odds-feed-specific spellings (e.g. a bookmaker's own short name),
 * which are unverifiable from ESPN alone. Add a specific pair here only once observed
 * live (watch fixtureUnconfirmed on production, per C-111's own disclosed limit) -
 * never a guessed spelling (rule 1: no fabricated data applies to reference tables too).
 */
export const FBS_NAME_ALIASES: ReadonlyMap<string, FbsConferenceTeam> = new Map([
  ...FBS_CONFERENCE_TEAMS.map((t): readonly [string, FbsConferenceTeam] => [t.displayName, t]),
  ...FBS_CONFERENCE_TEAMS.filter((t) => t.shortDisplayName !== t.displayName).map(
    (t): readonly [string, FbsConferenceTeam] => [t.shortDisplayName, t],
  ),
]);

/**
 * Resolve any of: ESPN numeric id, ESPN slug, or an ESPN-verified display/short name, to
 * its FBS team row. Returns null rather than guessing - a caller that gets null must
 * treat the fixture as unconfirmed (fixture-confirmation.ts's own rule), never invent a
 * match.
 */
export function resolveFbsTeam(identifier: string): FbsConferenceTeam | null {
  return (
    FBS_TEAM_BY_ESPN_ID.get(identifier) ??
    FBS_TEAM_BY_SLUG.get(identifier) ??
    FBS_NAME_ALIASES.get(identifier) ??
    null
  );
}

