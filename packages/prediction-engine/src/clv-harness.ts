/**
 * clv-harness.ts — Wave 4 of the 2026-09-04 all-night order (decision D2).
 *
 * CLV needs an open/entry line AND a close line. We have no historical
 * open/close archive, so a real CLV number cannot exist yet. This harness is
 * READY-FOR-DATA: the moment an archive lands, real CLV computes with zero new
 * math — because every calculation delegates to the existing clv.ts primitives
 * (computeSpreadClv / computeTotalClv / computeMoneylineClv). Nothing here
 * reimplements CLV arithmetic.
 *
 * Until then, a runner may inject a SYNTHETIC open (seeded jitter around the
 * close) to exercise the pipeline end to end. Every synthetic output must
 * carry the label from formatSyntheticOpenWarning(): it measures nothing about
 * the market and must never be quoted as a CLV result. Note the replay corpus
 * prices both sides at -110 and has no entry price distinct from the close —
 * CLV is degenerate there by construction (work order §1).
 */

import {
  computeMoneylineClv,
  computeSpreadClv,
  computeTotalClv,
  type MoneylineClvResult,
  type PointsClvResult,
  type SpreadSide,
  type TotalSide,
} from "./clv.js";

export type HarnessMarket = "SPREAD" | "TOTAL" | "MONEYLINE";
export type HarnessSide = SpreadSide | TotalSide;

export interface ClvEntry {
  readonly market: HarnessMarket;
  readonly side: HarnessSide;
  /** SPREAD only: HOME-perspective lines (repo convention, mirrors clv.ts). */
  readonly openHomeLine?: number | null;
  readonly closeHomeLine?: number | null;
  /** TOTAL only. */
  readonly openTotal?: number | null;
  readonly closeTotal?: number | null;
  /** MONEYLINE only: American odds FOR THE PICKED SIDE. */
  readonly openPrice?: number | null;
  readonly closePrice?: number | null;
}

export interface ClvEntryResult {
  /** Present for SPREAD/TOTAL when measurable. */
  readonly points: PointsClvResult | null;
  /** Present for MONEYLINE when measurable. */
  readonly probability: MoneylineClvResult | null;
  /** True when the close is missing: UNMEASURABLE, never a fabricated 0. */
  readonly unmeasurable: boolean;
  /** True when the "open" was synthesised by this harness, not observed. */
  readonly syntheticOpen: boolean;
}

export interface ClvEntryOptions {
  /** Marks the entry's open as synthetic — propagates into every summary. */
  readonly syntheticOpen?: boolean;
}

export function clvFromEntry(entry: ClvEntry, options: ClvEntryOptions = {}): ClvEntryResult {
  const syntheticOpen = options.syntheticOpen === true;
  const missing = (v: number | null | undefined): boolean => v === null || v === undefined || !Number.isFinite(v);

  if (entry.market === "SPREAD") {
    if (missing(entry.openHomeLine) || missing(entry.closeHomeLine)) {
      return { points: null, probability: null, unmeasurable: true, syntheticOpen };
    }
    return {
      points: computeSpreadClv(entry.openHomeLine!, entry.closeHomeLine!, entry.side as SpreadSide),
      probability: null,
      unmeasurable: false,
      syntheticOpen,
    };
  }

  if (entry.market === "TOTAL") {
    if (missing(entry.openTotal) || missing(entry.closeTotal)) {
      return { points: null, probability: null, unmeasurable: true, syntheticOpen };
    }
    return {
      points: computeTotalClv(entry.openTotal!, entry.closeTotal!, entry.side as TotalSide),
      probability: null,
      unmeasurable: false,
      syntheticOpen,
    };
  }

  // MONEYLINE
  if (missing(entry.openPrice) || missing(entry.closePrice)) {
    return { points: null, probability: null, unmeasurable: true, syntheticOpen };
  }
  return {
    points: null,
    probability: computeMoneylineClv(entry.openPrice!, entry.closePrice!),
    unmeasurable: false,
    syntheticOpen,
  };
}

/**
 * The exact label every synthetic-open output must carry. Do not soften, do not
 * reword: guards (brand lint, human review) grep for this string.
 */
export function formatSyntheticOpenWarning(): string {
  return (
    "SYNTHETIC OPEN — NOT A REAL CLV RESULT. Every 'open' in this output was " +
    "generated by a seeded jitter around the closing line to exercise the " +
    "pipeline. It measures nothing about the market and must never be quoted " +
    "as CLV. This harness is ready-for-data, not a measurement."
  );
}

/**
 * Deterministic synthetic open: seeded jitter around the close, snapped to the
 * half-point line grid, always within ±maxJitter. Same PRNG family as the
 * analytics scripts (mulberry32) so results are reproducible across runs.
 */
export function buildSyntheticOpen(close: number, maxJitter: number, opts: { seed: number }): number {
  let a = opts.seed >>> 0;
  a = (a + 0x6d2b79f5) >>> 0;
  let t = Math.imul(a ^ (a >>> 15), 1 | a);
  t = (t + Math.imul(t ^ (t >>> 14), 61 | t)) ^ t;
  const u = ((t ^ (t >>> 14)) >>> 0) / 4294967296; // one draw, deterministic per seed

  const raw = close + (u * 2 - 1) * maxJitter;
  let open = Math.round(raw * 2) / 2; // half-point grid
  if (Math.abs(open - close) > maxJitter) {
    // Snap-back to the nearest on-grid point inside the bound.
    const step = Math.floor(maxJitter * 2) / 2;
    open = close + Math.sign(open - close) * step;
  }
  return open;
}

export interface ArchiveColumn {
  readonly name: string;
  readonly required: boolean;
  readonly description: string;
}

/**
 * Exactly which columns a REAL open/close archive must supply before any real
 * CLV number can be produced. The entry price MUST be distinct from the close
 * (an archive where entry == close by construction produces degenerate CLV=0
 * everywhere — the known failure of replay-priced corpora).
 */
export function requiredArchiveColumns(): readonly ArchiveColumn[] {
  return [
    { name: "game_id", required: true, description: "Unique game key in the archive (joins to our gameKey)." },
    { name: "season", required: true, description: "Season, for per-season summaries and era splits." },
    { name: "game_date", required: true, description: "Kickoff timestamp; entry must precede it." },
    { name: "market", required: true, description: "SPREAD | TOTAL | MONEYLINE." },
    { name: "side", required: true, description: "HOME | AWAY (spread/ML) or OVER | UNDER (total)." },
    { name: "entry_line", required: true, description: "Line/price AT ENTRY TIME, same side and perspective as close_line. Must be able to differ from the close." },
    { name: "close_line", required: true, description: "Closing line/price for the same side and perspective." },
    { name: "book", required: false, description: "Source book; multi-book archives need a declared consistency policy." },
    { name: "entry_timestamp", required: false, description: "When the entry price was observable; enables entry-vs-open audits." },
  ] as const;
}
