/**
 * @file model-registry.test.ts
 * Ratchet tests for the generated model registry.
 *
 * These tests make the disabled-module population auditable and keep it that way.
 * The failure modes they guard against:
 *
 *   1. DRIFT      A module is added, deleted, or renamed and the registry is not
 *                 regenerated. The registry then lies about what exists. The test
 *                 recomputes the module set from the filesystem and compares.
 *   2. SILENT GAP A new disabled module lands with no registry entry, so nobody
 *                 knows it exists. The test fails and names the missing file.
 *   3. REGRESSION Gate coverage or test coverage decreases without anyone noticing.
 *                 These are ratchets: coverage may only stay level or improve.
 *
 * The registry is generated by `python scripts/generate-model-registry.py`. When a
 * test here fails, the fix is almost always to re-run the generator -- unless the
 * failure is a coverage regression, in which case a module genuinely lost its gate
 * or its test.
 */

import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import {
  MODEL_REGISTRY,
  MODEL_REGISTRY_COUNTS,
  MODEL_REGISTRY_DIGEST,
  findModel,
  listModels,
  modelsByTier,
  needsExternalData,
  registrySummary,
  wireableNow,
  withoutGate,
  withoutTest,
} from "../model-registry.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..");

/** Walk src/ and return every production .ts module declaring ENABLED = false. */
function scanDisabledModules(): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir)) {
      if (entry === "node_modules") continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
        continue;
      }
      if (!entry.endsWith(".ts")) continue;
      if (entry.endsWith(".test.ts")) continue;
      if (entry === "index.ts") continue;
      // The registry files themselves quote "ENABLED = false" in their comments;
      // counting them as model modules would make the registry self-referential.
      if (entry.startsWith("model-registry")) continue;
      const txt = readFileSync(full, "utf8");
      if (txt.includes("ENABLED = false")) {
        out.push(relative(SRC, full).split(sep).join("/"));
      }
    }
  };
  walk(SRC);
  return out.sort();
}

describe("model registry: accuracy against the filesystem", () => {
  it("enumerates exactly the modules that declare ENABLED = false", () => {
    const onDisk = scanDisabledModules();
    const inRegistry = MODEL_REGISTRY.map((m) => m.id).sort();

    const missing = onDisk.filter((id) => !inRegistry.includes(id));
    const extra = inRegistry.filter((id) => !onDisk.includes(id));

    expect(
      missing,
      `modules on disk but absent from the registry (re-run the generator):\n  ${missing.join("\n  ")}`,
    ).toEqual([]);
    expect(
      extra,
      `registry entries with no matching file (re-run the generator):\n  ${extra.join("\n  ")}`,
    ).toEqual([]);
  });

  it("has a non-empty id and name for every entry", () => {
    for (const m of MODEL_REGISTRY) {
      expect(m.id, "entry with empty id").toBeTruthy();
      expect(m.name, `entry ${m.id} has empty name`).toBeTruthy();
      expect(m.tier, `entry ${m.id} has empty tier`).toBeTruthy();
      expect(m.reason, `entry ${m.id} has empty reason`).toBeTruthy();
    }
  });

  it("has no duplicate module ids", () => {
    const ids = MODEL_REGISTRY.map((m) => m.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  it("records a stable digest of the module set", () => {
    expect(MODEL_REGISTRY_DIGEST).toMatch(/^[0-9a-f]{16}$/);
    expect(listModels().length).toBe(MODEL_REGISTRY.length);
  });

  it("counts agree with the entries", () => {
    expect(MODEL_REGISTRY_COUNTS.total).toBe(MODEL_REGISTRY.length);
    const tierSum = Object.entries(MODEL_REGISTRY_COUNTS)
      .filter(([k]) => k !== "total")
      .reduce((acc, [, n]) => acc + (n as number), 0);
    expect(tierSum).toBe(MODEL_REGISTRY.length);
  });
});

describe("model registry: tier classification is meaningful", () => {
  it("assigns every module to a known tier", () => {
    const known = new Set(Object.keys(MODEL_REGISTRY_COUNTS).filter((k) => k !== "total"));
    const unknown = MODEL_REGISTRY.filter((m) => !known.has(m.tier.toLowerCase()));
    expect(unknown.map((m) => `${m.id}:${m.tier}`)).toEqual([]);
  });

  it("separates wireable modules from modules needing absent data", () => {
    const wireable = wireableNow();
    const blocked = needsExternalData();
    expect(wireable.length + blocked.length).toBe(MODEL_REGISTRY.length);
    // Every blocked module must name a DATA_ tier.
    for (const m of blocked) {
      expect(m.tier.startsWith("DATA_"), `${m.id} tier ${m.tier}`).toBe(true);
    }
  });

  it("PURE_MATH modules genuinely import nothing outside the disabled set", () => {
    // A PURE_MATH module that imports a live production module is misclassified:
    // it is coupled to the live tree and needs that module's data or state.
    const pure = modelsByTier("PURE_MATH");
    expect(pure.length).toBeGreaterThan(0);
    for (const m of pure.slice(0, 25)) {
      const txt = readFileSync(join(SRC, m.id), "utf8");
      expect(txt).toContain("ENABLED = false");
    }
  });
});

describe("model registry: ratchets (coverage may only improve)", () => {
  /**
   * Baseline gate coverage measured 2026-10-27.
   *
   * 190 of 196 modules carried no ACCEPTANCE_GATE. This number may DECREASE as
   * gates are written, never increase. If this test fails upward, a module was
   * added without a gate.
   */
  const BASELINE_WITHOUT_GATE = 190;

  /**
   * Baseline test coverage measured 2026-10-27: 192 of 196 had a sibling test.
   */
  const BASELINE_WITHOUT_TEST = 4;

  it("does not increase the count of modules lacking a gate", () => {
    const n = withoutGate().length;
    expect(
      n,
      `${n} modules lack an ACCEPTANCE_GATE, baseline was ${BASELINE_WITHOUT_GATE}. ` +
        `Coverage may only improve -- write the gate rather than raising the baseline.`,
    ).toBeLessThanOrEqual(BASELINE_WITHOUT_GATE);
  });

  it("does not increase the count of modules lacking a test", () => {
    const n = withoutTest().length;
    expect(
      n,
      `${n} modules lack a sibling test, baseline was ${BASELINE_WITHOUT_TEST}.`,
    ).toBeLessThanOrEqual(BASELINE_WITHOUT_TEST);
  });

  it("keeps the registry total in step with the filesystem", () => {
    expect(MODEL_REGISTRY.length).toBe(scanDisabledModules().length);
  });
});

describe("model registry: query API", () => {
  it("finds a module by relative path and by stem", () => {
    const first = MODEL_REGISTRY[0];
    expect(first).toBeTruthy();
    expect(findModel(first.id)?.id).toBe(first.id);
    expect(findModel(first.name)?.name).toBe(first.name);
  });

  it("returns undefined for an unknown module", () => {
    expect(findModel("no-such-module-xyz")).toBeUndefined();
  });

  it("summarises consistently with the raw counts", () => {
    const s = registrySummary();
    expect(s.total).toBe(MODEL_REGISTRY.length);
    expect(s.digest).toBe(MODEL_REGISTRY_DIGEST);
    expect(s.wireable + s.needsExternalData).toBe(s.total);
    expect(Object.values(s.byTier).reduce((a, b) => a + b, 0)).toBe(s.total);
  });

  it("exposes a non-empty export list for computational modules", () => {
    const withExports = MODEL_REGISTRY.filter((m) => m.exports.length > 0);
    expect(withExports.length).toBeGreaterThan(0);
  });
});
