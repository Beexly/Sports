/**
 * Matchup Engine — the weekly read that turns the static GSE Rating into a
 * game-specific edge.
 *
 * The GSE Rating (processGrade) grades a player against his position over the
 * season. It is the right BASE number — but it says nothing about who the player
 * lines up against THIS week. A WR1 with an elite rating drawing a shutdown
 * secondary is a different bet than the same WR drawing the league's softest
 * coverage. Sharps adjust for exactly this; the engine does it explicitly.
 *
 * For the current (or most-recent scheduled) week we:
 *   1. Join every team to its opponent from the schedule (schedule-context.ts).
 *   2. Read that OPPONENT's defensive context from the deep data we already
 *      ingest:
 *        • team-environment.ts — opponent defensive EPA percentile (defEpaPct,
 *          where HIGH = stronger defense) and defensive success rate.
 *        • pressure-coverage.ts — pressure the opponent's defense generates
 *          (team-summed def pressures + blitzes) and coverage it allows
 *          (target-weighted passer rating allowed across its charted defenders).
 *        • team-environment.ts pace proxy (noHuddleRate) — tempo/extra-snaps the
 *          opponent's own offense tends to force, a (light) volume tailwind.
 *   3. Fold those opponent reads into a single MATCHUP DELTA in GSE-Rating
 *      points (a bounded adjustment, NOT a re-grade of the model), classify it
 *      favorable / neutral / tough, and write a one-line, plain-English note
 *      naming the REAL driver.
 *   4. Pair each player (from player-model.ts) with his team's opponent read to
 *      produce a matchup-adjusted row: base rating, delta, adjusted read,
 *      opponent, and the note.
 *
 * INTEGRITY (non-negotiable):
 *   • We do NOT change the model. processGrade and MODEL_VERSION are untouched.
 *     The matchup delta is a presentation-layer adjustment shown ALONGSIDE the
 *     base rating; the base rating is always carried through unmodified.
 *   • No fabricated data. Every driver is a real column. When a team's opponent
 *     has no environment/charting context (e.g. early in the season, or a team
 *     below a sample floor), the delta is null, the grade is "—" / unknown, and
 *     the note says so honestly. We never invent an opponent strength.
 *   • This is matchup CONTEXT, not a published forward projection or a pick.
 *     canPublishProjections stays false.
 *
 * SERVER engine: loads player-model, schedule-context, team-environment and
 * pressure-coverage on the server and returns a flat, serializable result. No
 * functions cross the RSC boundary — the page/client owns all render fns.
 * Pattern mirrors play-design.ts / team-environment.ts.
 */

