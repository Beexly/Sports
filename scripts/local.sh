#!/usr/bin/env bash
# ============================================================
# Sports Prediction Platform — local one-command bootstrap.
#
# Usage (from repo root):
#   bash scripts/local.sh           # set up everything + run app + worker
#   bash scripts/local.sh setup     # just set up (no run)
#   bash scripts/local.sh run       # just run app + worker (assumes setup done)
#   bash scripts/local.sh reset     # wipe DB volume and re-setup
#
# Safe to re-run. Every step is idempotent.
# ============================================================

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

log()  { printf '\033[1;34m[local]\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m[ ok  ]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[fail]\033[0m %s\n' "$*"; exit 1; }

# ── prereqs ─────────────────────────────────────────────────
check_prereqs() {
  command -v node >/dev/null || die "Node 20+ required. Install from https://nodejs.org"
  local node_major
  node_major="$(node -p 'process.versions.node.split(".")[0]')"
  [ "$node_major" -ge 20 ] || die "Node $node_major detected; need 20+"
  command -v npm >/dev/null  || die "npm required"
  command -v docker >/dev/null || die "Docker required. Install Docker Desktop."
  docker info >/dev/null 2>&1 || die "Docker daemon not running. Start Docker Desktop."
  ok "Prereqs OK (node $(node -v), docker running)"
}

# ── .env ────────────────────────────────────────────────────
write_env() {
  if [ -f .env ]; then
    ok ".env already exists (keeping yours)"
    return
  fi
  log "Writing .env with working local defaults + your Odds API key..."
  local secret
  secret="$(openssl rand -base64 32 2>/dev/null || node -e 'console.log(require("crypto").randomBytes(32).toString("base64"))')"
  cat > .env <<EOF
