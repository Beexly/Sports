  ok "Wrote .env"
}

link_envs() {
  local targets=(apps/web/.env packages/db/.env)
  for target in "${targets[@]}"; do
    if [ -L "$target" ]; then
      rm -f "$target"
    elif [ -e "$target" ]; then
      warn "$target exists as a regular file — keeping (remove manually to re-link)"
      continue
    fi
    ln -s ../../.env "$target"
  done
  ok "Linked .env into apps/web and packages/db"
}

# ── docker ──────────────────────────────────────────────────
start_docker_services() {
  log "Starting Postgres + Redis via docker compose..."
  docker compose -f docker/docker-compose.yml up -d
  log "Waiting for Postgres to accept connections..."
  local tries=0
  until docker exec sports_postgres pg_isready -U sports -q 2>/dev/null; do
    tries=$((tries+1))
    [ $tries -gt 60 ] && die "Postgres did not become ready within 60s"
    sleep 1
  done
  ok "Postgres + Redis are up"
}

# ── deps ────────────────────────────────────────────────────
install_deps() {
  if [ -d node_modules/.bin ]; then
    ok "node_modules already installed"
  else
    log "Running npm install (this takes ~1 min the first time)..."
    npm install
    ok "Dependencies installed"
  fi
}

# ── prisma ──────────────────────────────────────────────────
setup_database() {
  log "Generating Prisma client..."
  npm run db:generate --silent
  log "Pushing schema to Postgres..."
  npm run db:push --silent
  log "Seeding sports + leagues..."
  npm run db:seed --silent
  ok "Database ready"
}

# ── run ─────────────────────────────────────────────────────
run_all() {
  [ -f .env ] || die ".env missing — run: bash scripts/local.sh setup"
  log "Loading .env into shell..."
  set -a
  # shellcheck disable=SC1091
  . ./.env
  set +a

  log "Starting Next.js dev server on http://localhost:3000 ..."
  npm run dev > /tmp/sports-app.log 2>&1 &
  APP_PID=$!

  log "Starting data-refresh worker..."
  npm run start --workspace=workers/data-refresh > /tmp/sports-worker.log 2>&1 &
  WORKER_PID=$!

  cleanup() {
    echo
    log "Shutting down (app=$APP_PID worker=$WORKER_PID)..."
    kill "$APP_PID" "$WORKER_PID" 2>/dev/null || true
    wait "$APP_PID" "$WORKER_PID" 2>/dev/null || true
    ok "Stopped"
  }
  trap cleanup EXIT INT TERM

  # Wait for Next.js to be reachable
  local tries=0
  until curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1:3000/ 2>/dev/null | grep -qE '200|307|308'; do
    tries=$((tries+1))
    [ $tries -gt 60 ] && { tail -40 /tmp/sports-app.log; die "App did not start within 60s"; }
    sleep 1
  done
  ok "App is live: http://localhost:3000"

  cat <<BANNER

────────────────────────────────────────────────────────────
  🏈  Sports platform running
────────────────────────────────────────────────────────────
  App:      http://localhost:3000
  App log:  tail -f /tmp/sports-app.log
  Worker log: tail -f /tmp/sports-worker.log

  Ctrl-C to stop both.
────────────────────────────────────────────────────────────
BANNER

  # Stream both logs together until user hits Ctrl-C
  tail -n 0 -f /tmp/sports-app.log /tmp/sports-worker.log
}

# ── reset (destructive, explicit) ──────────────────────────
reset_all() {
  warn "Resetting: stopping containers and wiping Postgres volume."
  docker compose -f docker/docker-compose.yml down -v || true
  ok "Volumes wiped. Re-running setup..."
  setup_all
}

setup_all() {
  check_prereqs
  write_env
  link_envs
  start_docker_services
  install_deps
  setup_database
  ok "Setup complete."
}

case "${1:-all}" in
  setup) setup_all ;;
  run)   run_all ;;
  reset) reset_all ;;
  all|"") setup_all; run_all ;;
  *)     die "Unknown command: $1 (use: setup | run | reset | all)" ;;
esac
