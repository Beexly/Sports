# Postgres/Redis credentials match docker/docker-compose.yml.

DATABASE_URL="postgresql://sports:sports_dev_password@127.0.0.1:5432/sports_platform?schema=public"
DIRECT_URL="postgresql://sports:sports_dev_password@127.0.0.1:5432/sports_platform?schema=public"

NEXTAUTH_SECRET="${secret}"
NEXTAUTH_URL="http://localhost:3000"

GOOGLE_CLIENT_ID=""
GOOGLE_CLIENT_SECRET=""

STRIPE_SECRET_KEY="sk_test_placeholder"
STRIPE_WEBHOOK_SECRET="whsec_placeholder"
STRIPE_PRO_PRICE_ID="price_placeholder_pro"
STRIPE_ELITE_PRICE_ID="price_placeholder_elite"
NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY="pk_test_placeholder"

THE_ODDS_API_KEY="e7f1bc97f419509c7426bad7a2504019"

ANTHROPIC_API_KEY=""

REDIS_URL="redis://127.0.0.1:6379"

NODE_ENV="development"
NEXT_PUBLIC_APP_URL="http://localhost:3000"

# Bootstrap progression flags (safe defaults — see .env.example for the progression guide)
