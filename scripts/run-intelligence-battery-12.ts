async function runBattery() {
  console.log("================================================================================");
  console.log("EXECUTING ADDENDUM 4.1: TWELVE INTELLIGENCE BATTERY SCENARIOS");
  console.log("================================================================================");

  const fullCorpus = loadVerifiedMindCorpus();
  console.log(`Loaded ${fullCorpus.length} Verified Mind Principles for Battery Execution.\n`);

  const results: any[] = [];

  for (const scenario of BATTERY_SCENARIOS) {
    console.log(`[${scenario.id}] ${scenario.name}...`);
    const corpusToUse = scenario.customCorpus !== undefined ? scenario.customCorpus : fullCorpus;
    const vector = mapGameContextToVector(scenario.context);

    // Section 6.2/6.3 Evaluation
    const principlesEval = evaluateMindPrinciples(vector, corpusToUse);

    // Product Layer Evaluation (Pick, Parlay, DFS, Trace)
    const productEval = evaluateMindReasoning(scenario.context, corpusToUse as any);

    const scenarioResult = {
      scenario_id: scenario.id,
      name: scenario.name,
      description: scenario.description,
      context_vector: vector,
      principles_evaluation: {
        total_delta: principlesEval.total_delta,
        adjustments_count: principlesEval.adjustments.length,
        adjustments: principlesEval.adjustments,
        audit_records_count: principlesEval.audit_trail.length,
        rendered_prose_length: principlesEval.rendered_prose.length,
      },
      product_outputs: {
        applicable_principles_matched: productEval.applicablePrinciples.length,
        net_situational_adjustment: productEval.netSituationalAdjustment,
        situational_pick: {
          selection: productEval.situationalPick.selection,
          conviction: productEval.situationalPick.conviction,
          model_fair_probability: productEval.situationalPick.modelFairProbability,
          market_implied_probability: productEval.situationalPick.marketImpliedProbability,
          raw_edge: productEval.situationalPick.rawEdge,
          primary_citations: productEval.situationalPick.mindCitations.map(c => ({
            id: c.item_id,
            principle: c.principle_or_feature,
            quote: c.evidence_quote,
            delta: c.numericDelta,
          })),
        },
        same_game_parlay: {
          name: productEval.sameGameParlay.name,
          estimated_fair_odds: productEval.sameGameParlay.estimatedFairOdds,
          retail_independent_odds: productEval.sameGameParlay.retailIndependentOdds,
          correlation_advantage_pct: productEval.sameGameParlay.correlationAdvantagePct,
          copula_theta: productEval.sameGameParlay.copulaTheta,
          legs_count: productEval.sameGameParlay.legs.length,
        },
        fantasy_dfs: {
          matchup_overview: productEval.fantasyDfsAdvice.matchupOverview,
          cash_strategy: productEval.fantasyDfsAdvice.cashGameStrategy,
          gpp_strategy: productEval.fantasyDfsAdvice.tournamentGppStrategy,
          targets_count: productEval.fantasyDfsAdvice.targets.length,
        },
        master_reasoning_trace: productEval.reasoningTrace,
      },
    };

    results.push(scenarioResult);
    console.log(`   -> Total Delta: ${principlesEval.total_delta.toFixed(6)} | Pick: ${productEval.situationalPick.selection || "(none)"} (Fair: ${(productEval.situationalPick.modelFairProbability * 100).toFixed(1)}%) | Parlay Legs: ${productEval.sameGameParlay.legs.length}`);
  }

  const outDir = path.resolve("docs/predictions/research/2026-10-17");
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const outFile = path.join(outDir, "intelligence-battery-12-2026-10-17.json");
  fs.writeFileSync(outFile, JSON.stringify({
    execution_timestamp_utc: new Date().toISOString(),
    total_scenarios_evaluated: results.length,
    scenarios: results,
  }, null, 2), "utf-8");

  console.log("\n================================================================================");
  console.log(`ALL 12 INTELLIGENCE BATTERY SCENARIOS PERSISTED CLEANLY TO:`);
  console.log(outFile);
  console.log("================================================================================");
}

runBattery().catch(console.error);
