#!/usr/bin/env node
/**
 * Turn harvested artifacts into loadable SQL.
 *
 * This is the last mile between the harvest and the tables. It emits one .sql file with the
 * org upsert, one rival_assets row per artifact and prospect_contacts rows from the rolled-up
 * entrants, written as COPY from stdin so 100k contacts load in one statement instead of 100k
 * inserts.
 *
 * Confidence is deliberately not 100 for a handle. `emailHash` is a stable function of the
 * owner id, so re-loading the same person updates rather than duplicates, and a handle that is
 * not an email is marked with its own segment rather than pretending to be contactable mail.
 *
 * Usage:
 *   npx tsx scripts/competitive-intel/emit-sql.ts --in .ci-out --org fantasylabs --out .ci-out/load.sql
 *   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f .ci-out/load.sql
 *
 * Exit: 0 written, 2 nothing to read.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { engagementBand, rollUpEntrants, type RivalEntrant } from "../../packages/competitive-intel/src/adapters/fantasylabs-contests.js";
import type { Provenance } from "../../packages/competitive-intel/src/types.js";

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? undefined : process.argv[i + 1];
}

interface Artifact {
  provenance: Provenance;
  assetType: string;
  rowCount: number;
  rows: RivalEntrant[];
}

const inDir = arg("in") ?? ".ci-out";
const orgSlug = arg("org") ?? "fantasylabs";
const outPath = arg("out") ?? join(inDir, "load.sql");

const files = readdirSync(inDir).filter((f) => f.endsWith(".json") && !f.startsWith("ids"));
const artifacts: Artifact[] = [];
for (const file of files) {
  try {
    const parsed = JSON.parse(readFileSync(join(inDir, file), "utf8")) as Artifact;
    if (Array.isArray(parsed.rows) && parsed.provenance) artifacts.push(parsed);
  } catch {
    // ids.json and the markdown brief are not artifacts; skip quietly.
  }
}
if (artifacts.length === 0) {
  console.error(`no artifacts in ${inDir}`);
  process.exit(2);
}

/** The org id is derived, not random, so repeated loads hit the same row. */
const orgId = `org_${orgSlug}`;
const stableId = (prefix: string, seed: string): string =>
  `${prefix}_${createHash("sha256").update(`${orgSlug}:${seed}`).digest("hex").slice(0, 24)}`;
const emailHashFor = (ownerId: number): string =>
  createHash("sha256").update(`${orgSlug}:owner:${ownerId}`).digest("hex").slice(0, 40);

const q = (value: string | number | boolean | null): string => {
  if (value === null) return "\\N";
  if (typeof value === "boolean") return value ? "t" : "f";
  if (typeof value === "number") return String(value);
  return value.replace(/\\/g, "\\\\").replace(/\t/g, "\\t").replace(/\n/g, "\\n");
};

const lines: string[] = [];
lines.push("-- generated by scripts/competitive-intel/emit-sql.ts, do not hand edit");
lines.push("BEGIN;");
lines.push(
  `INSERT INTO "rival_orgs" ("id","slug","name","tier","verdict","firstSeenAt") VALUES ` +
    `('${orgId}','${q(orgSlug)}','${q(orgSlug)}','B','active',CURRENT_TIMESTAMP) ` +
    `ON CONFLICT ("slug") DO UPDATE SET "verdict" = 'active';`,
);

lines.push(
  `COPY "rival_assets" ("id","orgId","assetType","url","httpStatus","byteSize","sourceUrl","retrievedAt","harvestTier","licenseClass","commercialOk","contentHash") FROM STDIN;`,
);
for (const artifact of artifacts) {
  const p = artifact.provenance;
  lines.push(
    [
      stableId("ra", p.content_hash + p.source_url),
      orgId,
      q(p.source_url.includes("usernames") ? "pick_archive" : "projection_file"),
      q(p.source_url),
      200,
      "\N",
      q(p.source_url),
      p.retrieved_at,
      p.harvest_tier,
      q(p.license_class),
      q(p.commercial_ok),
      q(p.content_hash),
    ].join("\t"),
  );
}
lines.push("\\.");


const entrantRows = artifacts
  .filter((a) => a.assetType === "pick_archive" || a.rows.every((r) => "contestId" in r))
  .flatMap((a) => a.rows);
const profiles = rollUpEntrants(entrantRows);

lines.push(
  `COPY "prospect_contacts" ("id","orgId","emailHash","handle","platform","segment","confidence","sourceUrl","createdAt") FROM STDIN;`,
);
for (const profile of profiles) {
  lines.push(
    [
      stableId("pc", `owner:${profile.ownerId}`),
      orgId,
      q(emailHashFor(profile.ownerId)),
      q(profile.username),
      "fantasylabs",
      q(engagementBand(profile)),
      engagementBand(profile) === "whale" ? 80 : engagementBand(profile) === "grinder" ? 70 : 60,
      q(`https://www.fantasylabs.com/contests/${profile.ownerId}`),
      new Date().toISOString(),
    ].join("\t"),
  );
}
lines.push("\\.");
lines.push("COMMIT;");

writeFileSync(outPath, `${lines.join("\n")}\n`);
console.log(`[emit-sql] ${artifacts.length} artifact(s), ${profiles.length} contact(s) -> ${outPath}`);
console.log(`[emit-sql] load with: psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f ${outPath}`);
